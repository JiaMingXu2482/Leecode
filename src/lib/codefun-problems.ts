// 分类树，刷题计划页按这个分组展示（顺序即刷题顺序）。
// ids 存的是 P 号数字，和 codefunFrontendId 一样按 CODEFUN_ID_BASE 偏移。
export const CODEFUN_TOPIC_GROUPS: { name: string; ids: number[] }[] = (() => {
  const groups: { name: string; ids: number[] }[] = [];
  for (const [pid, , category] of CODEFUN_PROBLEMS) {
    const id = Number(pid.slice(1));
    const last = groups[groups.length - 1];
    if (last && last.name === category) {
      last.ids.push(id);
    } else {
      groups.push({ name: category, ids: [id] });
    }
  }
  return groups;
})();

const CF_BY_PID_NUMBER = new Map(
  CODEFUN_PROBLEMS.map(([pid, difficulty, category, title, origin]) => [
    Number(pid.slice(1)),
    { pid, difficulty, category, title, origin },
  ]),
);

// 传入 P 号数字（frontendId - CODEFUN_ID_BASE），不是数组下标
export function codefunTopicForPid(pidNumber: number): string {
  return CF_BY_PID_NUMBER.get(pidNumber)?.category ?? "其他";
}

// 界面上显示的题号（"P4520"）。题目不在题单里时回退成 P + 数字。
export function codefunDisplayId(pidNumber: number): string {
  return CF_BY_PID_NUMBER.get(pidNumber)?.pid ?? `P${pidNumber}`;
}
