// 分类树，刷题计划页按这个分组展示（顺序即刷题顺序）
export const CODEFUN_TOPIC_GROUPS: { name: string; ids: number[] }[] = (() => {
  const groups: { name: string; ids: number[] }[] = [];
  CODEFUN_PROBLEMS.forEach(([, , category], index) => {
    const last = groups[groups.length - 1];
    if (last && last.name === category) {
      last.ids.push(index + 1);
    } else {
      groups.push({ name: category, ids: [index + 1] });
    }
  });
  return groups;
})();

const CF_TOPIC_BY_INDEX = new Map<number, string>();
CODEFUN_PROBLEMS.forEach(([, , category], index) => CF_TOPIC_BY_INDEX.set(index + 1, category));

// 传入 1-based 序号（不是 frontendId）
export function codefunTopicForIndex(index: number): string {
  return CF_TOPIC_BY_INDEX.get(index) ?? "其他";
}
