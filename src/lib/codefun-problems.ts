export const CODEFUN_ID_BASE = 20000;

export function codefunFrontendId(index: number) {
  return CODEFUN_ID_BASE + index;
}

export function isCodefunFrontendId(frontendId: number) {
  return frontendId > CODEFUN_ID_BASE;
}

// 机考分值直接对应难度：100 分是签到题，300 分是压轴题。
export function difficultyForScore(score: number) {
  if (score <= 100) return "EASY" as const;
  if (score <= 200) return "MEDIUM" as const;
  return "HARD" as const;
}

